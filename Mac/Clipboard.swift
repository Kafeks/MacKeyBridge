import Cocoa
import CryptoKit

// MARK: - Clipboard sync (protocol 3)
//
// Two-way: whatever is copied on the Mac is sent to Windows, and whatever Windows sends is put on the Mac clipboard.
// Text (UTF-8) and images (PNG) are synced; files are not. The general pasteboard is polled (macOS has no change
// notification) every 0.4 s. A change is sent only if:
//   * sync is on here AND on Windows (each side announces its state with CLIP_STATE),
//   * the content was not put there by us (change count recorded after every write),
//   * it is not the same content as the last one sent or received (SHA-256), so nothing ping-pongs,
//   * the app that copied it did not mark it as a password / transient (nspasteboard.org conventions).
// Everything here runs on the main thread; `linkStateChanged` and `handle` hop onto it.

/// Pasteboard types that password managers and other apps use to say "do not record or sync this".
let clipboardPrivateTypes: Set<String> = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
]

enum ClipDirection: Equatable { case toWindows, fromWindows }

struct ClipTransfer: Equatable {
    let direction: ClipDirection
    let isImage: Bool
    let summary: String
    let date: Date
}

func clipboardHash(kind: UInt8, payload: Data) -> Data {
    var h = SHA256()
    h.update(data: Data([kind]))
    h.update(data: payload)
    return Data(h.finalize())
}

func byteCountText(_ n: Int) -> String {
    return ByteCountFormatter.string(fromByteCount: Int64(n), countStyle: .file)
}

final class ClipboardSync {
    private let link: Link
    private let pb = NSPasteboard.general
    private var lastChangeCount: Int
    private var lastHash: Data?
    private var timer: Timer?

    /// Local switches (saved in the preferences by the window).
    var enabled = true {
        didSet { if enabled != oldValue { sendState() } }
    }
    var includeImages = true {
        didSet { if includeImages != oldValue { sendState() } }
    }

    /// What Windows announced; nil = not known yet (or the Windows app is too old for clipboard sync).
    private(set) var remoteEnabled: Bool?
    private(set) var remoteImages = false
    /// systemUptime of the last transfer in either direction (activity light).
    private(set) var lastActivity = -100.0

    var onUpdate: (() -> Void)?
    var onTransfer: ((ClipTransfer) -> Void)?

    init(link: Link) {
        self.link = link
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    var peerSupportsClipboard: Bool { link.connected && link.peerProtocol >= 3 }

    /// Clipboard contents flow only when both sides want it.
    var active: Bool { enabled && peerSupportsClipboard && remoteEnabled == true }

    // MARK: link events (link thread)

    func linkStateChanged(_ st: LinkState) {
        DispatchQueue.main.async { [self] in
            remoteEnabled = nil
            remoteImages = false
            if st == .connected { sendState() }
            onUpdate?()
        }
    }

    func handle(_ m: PeerMessage) {
        DispatchQueue.main.async { [self] in
            switch m {
            case .clipboardState(let on, let images):
                if remoteEnabled != on {
                    say(on ? "Clipboard sync is on in the Windows app" : "Clipboard sync is off in the Windows app")
                }
                remoteEnabled = on
                remoteImages = images
                onUpdate?()
            case .clipboard(let kind, let data):
                apply(kind: kind, data: data)
            }
        }
    }

    func sendState() {
        guard peerSupportsClipboard else { return }
        var flags: UInt8 = 0
        if enabled { flags |= clipFlagOn }
        if enabled && includeImages { flags |= clipFlagImages }
        link.enqueue([pktClipState, flags])
    }

    // MARK: Mac -> Windows

    private func poll() {
        let cc = pb.changeCount
        guard cc != lastChangeCount else { return }
        lastChangeCount = cc
        guard active else { return }

        let types = Set((pb.types ?? []).map { $0.rawValue })
        if !types.isDisjoint(with: clipboardPrivateTypes) {
            say("Clipboard: not sent - the app that copied it marked it as a password or temporary")
            return
        }
        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) {
            say("Clipboard: files are not synced (only text and images)")
            return
        }

        var kind: UInt8 = 0
        var payload = Data()
        var summary = ""
        if let s = pb.string(forType: .string), !s.isEmpty {
            kind = clipKindText
            payload = Data(s.utf8)
            summary = textSummary(s)
        } else if includeImages && remoteImages, let img = readImage() {
            kind = clipKindPNG
            payload = img.png
            summary = "Image · \(img.w)×\(img.h) · \(byteCountText(img.png.count))"
        } else {
            return  // nothing we can sync (or images are switched off)
        }
        guard payload.count <= clipMaxBytes else {
            say("Clipboard: not sent - \(byteCountText(payload.count)) is over the \(byteCountText(clipMaxBytes)) limit")
            return
        }
        let h = clipboardHash(kind: kind, payload: payload)
        if h == lastHash { return }  // Windows already has exactly this
        lastHash = h
        link.enqueue(clipboardPacket(kind: kind, payload: payload))
        record(ClipTransfer(direction: .toWindows, isImage: kind == clipKindPNG, summary: summary, date: Date()))
    }

    private func readImage() -> (png: Data, w: Int, h: Int)? {
        if let d = pb.data(forType: .png), let rep = NSBitmapImageRep(data: d) {
            return (d, rep.pixelsWide, rep.pixelsHigh)
        }
        if let t = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: t),
           let png = rep.representation(using: .png, properties: [:]) {
            return (png, rep.pixelsWide, rep.pixelsHigh)
        }
        return nil
    }

    // MARK: Windows -> Mac

    private func apply(kind: UInt8, data: Data) {
        guard enabled else { return }
        let summary: String
        switch kind {
        case clipKindText:
            guard let s = String(data: data, encoding: .utf8) else {
                say("Clipboard: received text that is not valid UTF-8 - ignored")
                return
            }
            pb.clearContents()
            pb.setString(s, forType: .string)
            summary = textSummary(s)
        case clipKindPNG:
            guard includeImages else { return }
            guard let rep = NSBitmapImageRep(data: data) else {
                say("Clipboard: received an image that cannot be read - ignored")
                return
            }
            pb.clearContents()
            pb.setData(data, forType: .png)
            if let tiff = rep.tiffRepresentation { pb.setData(tiff, forType: .tiff) }  // many Mac apps paste TIFF only
            summary = "Image · \(rep.pixelsWide)×\(rep.pixelsHigh) · \(byteCountText(data.count))"
        default:
            return  // a format from a newer version: ignore
        }
        lastChangeCount = pb.changeCount  // our own write: do not send it back
        lastHash = clipboardHash(kind: kind, payload: data)
        record(ClipTransfer(direction: .fromWindows, isImage: kind == clipKindPNG, summary: summary, date: Date()))
    }

    private func textSummary(_ s: String) -> String {
        let n = s.count
        return "Text · \(n) character" + (n == 1 ? "" : "s")
    }

    private func record(_ t: ClipTransfer) {
        lastActivity = ProcessInfo.processInfo.systemUptime
        say("Clipboard \(t.direction == .toWindows ? "→ Windows" : "← Windows"): \(t.summary)")
        onTransfer?(t)
    }
}
